/**
 * Build options for the build planner: how athletes in a role are typically built, what that
 * build is good for, what it costs, and how they train. Described by sport and role, never by a
 * named person or their photo. Each build has figure proportions so the app can draw it (see
 * figure.ts): a picture of the shape, not of a real person. General strength-and-conditioning
 * knowledge; the planner adapts it to the student's age, equipment, schedule and injuries.
 */
import type { SportId } from '../sports/catalog';

export type BuildGroup = 'sport' | 'everyday';
export type Region = 'shoulders' | 'chest' | 'back' | 'arms' | 'core' | 'hips' | 'legs' | 'calves' | 'neck';

/** Proportions for the drawing (front view, in SVG units at 1x height). */
export interface Figure {
  /** Height relative to average (0.9 short – 1.1 tall). */
  h: number;
  /** Half-widths: shoulders, chest, lats (under the arms), waist, hips, neck. */
  S: number;
  C: number;
  L: number;
  W: number;
  H: number;
  N: number;
  /** Radii: deltoid, upper arm, forearm, thigh, calf. */
  d: number;
  A: number;
  Fa: number;
  T: number;
  c: number;
}

export interface BuildArchetype {
  id: string;
  group: BuildGroup;
  /** Sports this build belongs to (for grouping in the picker). */
  sports: SportId[];
  name: string;
  /** Who is typically built like this. */
  seenIn: string;
  look: string[];
  /** What this build does for you. */
  benefits: string[];
  /** What it costs or doesn't do. */
  tradeoffs: string[];
  training: string[];
  /** What's realistic: genetics, height, time. */
  realityCheck: string;
  figure: Figure;
  /** Areas the drawing highlights: where this build carries its muscle. */
  emphasis: Region[];
}

type FigArr = [h: number, S: number, C: number, L: number, W: number, H: number, N: number, d: number, A: number, Fa: number, T: number, c: number];
const fig = ([h, S, C, L, W, H, N, d, A, Fa, T, c]: FigArr): Figure => ({ h, S, C, L, W, H, N, d, A, Fa, T, c });

